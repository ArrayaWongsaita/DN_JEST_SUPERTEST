import { add } from "./add";

// ================================================
// บทที่ 01: test แรก
// ฝึก: test, expect, toBe
// ตัวอย่าง: expect(1 + 1).toBe(2);
// ================================================


// ------------------------------------------------
// ข้อ 1: add(1, 2) ต้องได้ 3
// แนวทาง: expect(ค่าที่ได้จริง).toBe(ค่าที่คาดหวัง)
// ------------------------------------------------
// test.todo("add(1, 2) ต้องได้ 3");
// 👉 เขียน test ของข้อ 1 ตรงนี้
test("add(1, 2) ต้องได้ 3", () => {
    const result = add(1,2)

    expect(result).toBe(3)
})


// ------------------------------------------------
// ข้อ 2: add(-1, 1) ต้องได้ 0
// แนวทาง: expect(add(...)).toBe(...)
// ------------------------------------------------
// test.todo("add(-1, 1) ต้องได้ 0");
// 👉 เขียน test ของข้อ 2 ตรงนี้
test("add(-1, 1) ต้องได้ 0", () => {
    expect(add(-1,1)).toBe(0)
})

// ------------------------------------------------
// ข้อ 3: add(0, 0) ต้องได้ 0
// แนวทาง: expect(add(...)).toBe(...)
// ------------------------------------------------
// test.todo("add(0, 0) ต้องได้ 0");
// 👉 เขียน test ของข้อ 3 ตรงนี้
test("add(0, 0) ต้องได้ 0", () => {
    expect(add(0,0)).toBe(0)
})