import { multiply } from "./multiply";

// ================================================
// บทที่ 01: test แรก
// ฝึก: test, expect, toBe
// ตัวอย่าง: expect(1 + 1).toBe(2);
// ================================================


// ------------------------------------------------
// ข้อ 1: multiply(2, 3) ต้องได้ 6
// แนวทาง: expect(ค่าที่ได้จริง).toBe(ค่าที่คาดหวัง)
// ------------------------------------------------
test("multiply(2, 3) ต้องได้ 6", () => {
  expect(multiply(2, 3)).toBe(6);
});


// ------------------------------------------------
// ข้อ 2: multiply(5, 0) ต้องได้ 0
// แนวทาง: expect(multiply(...)).toBe(...)
// ------------------------------------------------
test("multiply(5, 0) ต้องได้ 0", () => {
  expect(multiply(5, 0)).toBe(0);
});


// ------------------------------------------------
// ข้อ 3: multiply(-2, 4) ต้องได้ -8
// แนวทาง: expect(multiply(...)).toBe(...)
// ------------------------------------------------
test("multiply(-2, 4) ต้องได้ -8", () => {
  expect(multiply(-2, 4)).toBe(-8);
});
