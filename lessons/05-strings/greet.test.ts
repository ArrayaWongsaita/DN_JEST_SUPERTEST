import { greet } from "./greet";

// ================================================
// บทที่ 05: ข้อความ
// ฝึก: toMatch, toContain (กับข้อความ)
// ================================================


// ------------------------------------------------
// ข้อ 1: greet("Mali") ต้องได้ "Hello, Mali!"
// แนวทาง: ใช้ toBe เหมือนบทแรก
// ------------------------------------------------
test("greet(\"Mali\") ต้องได้ \"Hello, Mali!\"", () => {
  expect(greet("Mali")).toBe("Hello, Mali!");
});


// ------------------------------------------------
// ข้อ 2: greet("Somchai") ต้องมีคำว่า "Somchai"
// แนวทาง: ใช้ toContain เช็คว่าข้อความมีคำนี้อยู่ข้างใน
// ------------------------------------------------
test("greet(\"Somchai\") ต้องมีคำว่า \"Somchai\"", () => {
  expect(greet("Somchai")).toContain("Somchai");
});


// ------------------------------------------------
// ข้อ 3: greet("Mali") ต้องขึ้นต้นด้วย "Hello"
// แนวทาง: ใช้ toMatch ร่วมกับ regex โดย ^ แปลว่า "ขึ้นต้นด้วย" เช่น /^Hello/
// ------------------------------------------------
test("greet(\"Mali\") ต้องขึ้นต้นด้วย \"Hello\"", () => {
  expect(greet("Mali")).toMatch(/^Hello/);
});
