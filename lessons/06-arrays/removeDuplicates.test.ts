import { removeDuplicates } from "./removeDuplicates";

// ================================================
// บทที่ 06: array
// ฝึก: toContain (กับ array), toHaveLength
// ตัวอย่าง: expect(["a", "b"]).toContain("a");
// ================================================


// ------------------------------------------------
// ข้อ 1: removeDuplicates([1, 1, 2, 3, 3]) ต้องเหลือ 3 ตัว
// แนวทาง: ใช้ toHaveLength
// ------------------------------------------------
test("removeDuplicates([1, 1, 2, 3, 3]) ต้องเหลือ 3 ตัว", () => {
  expect(removeDuplicates([1, 1, 2, 3, 3])).toHaveLength(3);
});


// ------------------------------------------------
// ข้อ 2 (เลือกเอง): removeDuplicates([1, 1, 2, 3, 3]) ต้องได้ [1, 2, 3]
// แนวทาง: เลือก matcher เองว่าจะใช้ตัวไหน
// ------------------------------------------------
test("removeDuplicates([1, 1, 2, 3, 3]) ต้องได้ [1, 2, 3]", () => {
  expect(removeDuplicates([1, 1, 2, 3, 3])).toEqual([1, 2, 3]);
});
