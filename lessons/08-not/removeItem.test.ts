import { removeItem } from "./removeItem";

// ================================================
// บทที่ 08: not
// ฝึก: .not (กลับด้านผลของ matcher)
// ตัวอย่าง: expect(5).not.toBe(3);
// ================================================


// ------------------------------------------------
// ข้อ 1: removeItem(["a", "b", "c"], "b") ต้องไม่มี "b"
// แนวทาง: ใช้ not กับ toContain
// ------------------------------------------------
test("removeItem([\"a\", \"b\", \"c\"], \"b\") ต้องไม่มี \"b\"", () => {
  expect(removeItem(["a", "b", "c"], "b")).not.toContain("b");
});


// ------------------------------------------------
// ข้อ 2: removeItem(["a", "b", "c"], "b") ความยาวต้องไม่ใช่ 3
// แนวทาง: ใช้ not กับ toHaveLength
// ------------------------------------------------
test("removeItem([\"a\", \"b\", \"c\"], \"b\") ความยาวต้องไม่ใช่ 3", () => {
  expect(removeItem(["a", "b", "c"], "b")).not.toHaveLength(3);
});


// ------------------------------------------------
// ข้อ 3: removeItem ต้องคืน array ตัวใหม่ ไม่ใช่ตัวเดิม
// แนวทาง: เก็บ array ตั้งต้นไว้ในตัวแปร แล้วใช้ not กับ toBe เทียบกับผลที่ได้
// ------------------------------------------------
test("removeItem ต้องคืน array ตัวใหม่ ไม่ใช่ตัวเดิม", () => {
  const items = ["a", "b", "c"];
  const result = removeItem(items, "b");
  expect(result).not.toBe(items);
});
