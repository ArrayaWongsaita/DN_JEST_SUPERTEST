import { addItem, getItems, getTotal, clearCart } from "./cart";

// ================================================
// บทที่ 10: จัดกลุ่ม test และเตรียมของก่อนทุก test
// ฝึก: describe, beforeEach
//
// describe ใช้จัดกลุ่ม test ที่เกี่ยวกัน
// beforeEach คือโค้ดที่จะรัน "ก่อนทุก test" ในกลุ่มนั้น
//
// ตัวอย่างเต็มรูป:
//   describe("ชื่อกลุ่ม", () => {
//     beforeEach(() => {
//       // เตรียมของให้พร้อมก่อนแต่ละ test
//     });
//
//     test("...", () => {
//       // ...
//     });
//   });
//
// หมายเหตุ: ตะกร้าใน cart.ts เก็บของไว้ในตัวแปรของไฟล์ จึง "จำ" ของจาก test ก่อนหน้า
// ================================================


// ------------------------------------------------
// ข้อ 1: สร้าง describe("cart", () => { ... }) แล้วย้าย test ทุกข้อเข้าไปข้างใน
// แนวทาง: เขียน describe ครอบ test ทุกข้อที่เหลือ
// ------------------------------------------------
describe("cart", () => {
  // ------------------------------------------------
  // ข้อ 4: เพิ่ม beforeEach(() => clearCart()) ไว้บนสุดใน describe แล้วรันใหม่
  // แนวทาง: beforeEach(() => { clearCart(); }); วางตรงนี้ได้เลย (ข้างใน describe)
  // ------------------------------------------------
  beforeEach(() => {
    clearCart();
  });


  // ------------------------------------------------
  // ข้อ 2: addItem 1 ชิ้น แล้วตะกร้าต้องมี 1 ชิ้น
  // แนวทาง: addItem({ name: "Pen", price: 10 }) แล้วใช้ toHaveLength กับ getItems()
  // ------------------------------------------------
  test("addItem 1 ชิ้น แล้วตะกร้าต้องมี 1 ชิ้น", () => {
    addItem({ name: "Pen", price: 10 });
    expect(getItems()).toHaveLength(1);
  });


  // ------------------------------------------------
  // ข้อ 3: addItem อีก 1 ชิ้นใน test ใหม่ ตะกร้าต้องมี 1 ชิ้น
  // แนวทาง: addItem({ name: "Book", price: 100 }) แล้วใช้ toHaveLength(1) เหมือนข้อ 2
  // รันแล้วข้อนี้จะ fail ไม่ต้องตกใจ ลองอ่านว่า Received เป็นเท่าไหร่ แล้วไปทำข้อ 4
  // ------------------------------------------------
  test("addItem อีก 1 ชิ้นใน test ใหม่ ตะกร้าต้องมี 1 ชิ้น", () => {
    addItem({ name: "Book", price: 100 });
    expect(getItems()).toHaveLength(1);
  });


  // ------------------------------------------------
  // ข้อ 5: addItem ราคา 10 และ 100 แล้ว getTotal ต้องได้ 110
  // แนวทาง: addItem สองครั้ง แล้วใช้ toBe กับ getTotal()
  // ------------------------------------------------
  test("addItem ราคา 10 และ 100 แล้ว getTotal ต้องได้ 110", () => {
    addItem({ name: "Pen", price: 10 });
    addItem({ name: "Book", price: 100 });
    expect(getTotal()).toBe(110);
  });


  // ------------------------------------------------
  // ข้อ 6: ตะกร้าที่ยังไม่ได้เพิ่มอะไรต้องว่าง
  // แนวทาง: ใช้ toEqual([]) กับ getItems()
  // ------------------------------------------------
  test("ตะกร้าที่ยังไม่ได้เพิ่มอะไรต้องว่าง", () => {
    expect(getItems()).toEqual([]);
  });
});
